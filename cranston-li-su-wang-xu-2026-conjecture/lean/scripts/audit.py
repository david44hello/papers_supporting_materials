#!/usr/bin/env python3
"""audit.py — the coverage-and-assumptions table for every paper claim, produced by Lean itself.
Author: Dave Goel. Copyright (C) Dave Goel 2026--now. Licensed under the Apache License 2.0; see LICENSE.
## version 2.00 — the map of the short paper's version 2.00; a retired row; the summary counts the rows by their place.

For every `theorem` in EulerFlow/Paper/Statements.lean this script asks Lean (`#print axioms`) which axioms the proof
depends on, and classifies it:
  PROVED            only Lean's three standard axioms (propext, Classical.choice, Quot.sound)
  PROVED-FROM-CITED standard axioms plus EulerFlow.Cited.* axioms (the paper's cited results) — listed by name
  PROVED-FROM-TEMP  uses a EulerFlow.Cited.Temp.* axiom: a fact the paper PROVES that Lean has not proved yet — NOT done
  OPEN              depends on sorryAx (a proof gap somewhere below it)
  VIOLATION         any other axiom (forbidden; fails loudly)
Usage: scripts/audit.py            (writes AUDIT.md, exits 1 on any VIOLATION)
       scripts/audit.py --test     (self-test of the parser)
"""
import os
import re
import subprocess
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
STATEMENTS = PROJECT / "EulerFlow" / "Paper" / "Statements.lean"
AUDIT_LEAN = PROJECT / "EulerFlow" / "Audit.lean"
AUDIT_MD = PROJECT / "AUDIT.md"
SHORT_VERSION = "2.00"  # the SHORT paper FINAL text the map and the column refer to (tex md5 d0a6c9cf)
SHORT_MAP = PROJECT / f"SHORT_MAP_v{SHORT_VERSION}.tsv"  # Lean name -> place in the SHORT paper
AUDIT_NOTES = PROJECT / "AUDIT_NOTES.md"  # hand-written route/not-formalized notes, appended verbatim
CORE = os.environ.get("EULERFLOW_CORE", "1")  # the processor core the Lean run is pinned to
STANDARD = {"propext", "Classical.choice", "Quot.sound"}
NAMESPACE = "EulerFlow"
RIGHTS = "Copyright (C) Dave Goel 2026--now. Licensed under the Apache License 2.0; see LICENSE."
NOT_IN_SHORT = "not in the short paper"  # a result of the expanded version only
RETIRED = f"retired: no longer printed in version {SHORT_VERSION}"
TRUST_NOTE = ("**Trust.** No proof here takes a cited result as an input: there is NO EulerFlow/Cited/ folder and no "
              "project axiom. A PROVED row rests only on Lean's three standard axioms.")


def parse_statements(text):
    """Return [(name, doc_first_line)] for every top-level theorem, in file order."""
    items = []
    doc = ""
    for block in re.finditer(r"(/--((?:(?!-/).)*?)-/\s*)?^theorem\s+(\w+)", text, re.S | re.M):
        doc = " ".join((block.group(2) or "").split())
        items.append((block.group(3), doc[:140].replace("|", "\\|")))  # a raw | would split the table cell
    return items


def write_audit_lean(names):
    lines = ["-- GENERATED by scripts/audit.py — do not edit.", "-- " + RIGHTS, "import EulerFlow.Paper.Statements", ""]
    lines += [f"#print axioms {NAMESPACE}.{name}" for name in names]
    content = "\n".join(lines) + "\n"
    # Rewrite only on change: an identical rewrite leaves Lake's (content-hash) build fresh but makes the source
    # newer than its olean, and scripts/kernel_replay.sh then refuses the run as stale.
    if not AUDIT_LEAN.exists() or AUDIT_LEAN.read_text() != content:
        AUDIT_LEAN.write_text(content)


def run_lean():
    env = dict(os.environ, LEAN_NUM_THREADS="1")
    proc = subprocess.run(["nice", "-n", "19", "taskset", "-c", CORE, "lake", "build", "EulerFlow.Audit"],
                          cwd=PROJECT, capture_output=True, text=True, env=env)
    if proc.returncode != 0:
        sys.exit("AUDIT FAILED: Lean reported an error:\n" + proc.stdout + proc.stderr)
    return proc.stdout + proc.stderr


def parse_axioms(output, names):
    """Map each theorem name to its set of axioms, from `#print axioms` output."""
    result = {}
    pattern = re.compile(r"'([\w.]+)' (?:depends on axioms: \[(.*?)\]|does not depend on any axioms)", re.S)
    for match in pattern.finditer(output):
        full = match.group(1)
        short = full.removeprefix(NAMESPACE + ".")
        axioms = {a.strip() for a in (match.group(2) or "").replace("\n", " ").split(",") if a.strip()}
        result[short] = axioms
    missing = [n for n in names if n not in result]
    if missing:
        sys.exit(f"AUDIT FAILED: no #print axioms output for {missing}")
    return result


def classify(axioms):
    forbidden = {name for name in axioms - STANDARD - {"sorryAx"}
                 if not name.startswith("EulerFlow.Cited.")}
    if forbidden:
        return "VIOLATION"
    if "sorryAx" in axioms:
        return "OPEN"
    if any(a.startswith("EulerFlow.Cited.Temp.") for a in axioms):
        return "PROVED-FROM-TEMP"
    extra = axioms - STANDARD
    if not extra:
        return "PROVED"
    if all(a.startswith("EulerFlow.Cited.") for a in extra):
        return "PROVED-FROM-CITED"
    return "VIOLATION"


def short_cell(ref, lines):
    """The table cell for one row of the map: its place in the short paper, or why it has none."""
    if ref.upper().startswith("NOT IN SHORT PAPER"):
        return NOT_IN_SHORT
    if ref.upper().startswith("RETIRED"):
        return RETIRED
    return f"{ref}, {lines}".replace("|", "\\|")


def read_short_map():
    """Lean name -> "Lemma 7.2, l.531-533" (or NOT_IN_SHORT, or RETIRED). A theorem without a row fails loudly."""
    import csv
    with open(SHORT_MAP, newline="") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    return {r["lean_name"]: short_cell(r["short_ref"].strip(), r["short_lines"].strip()) for r in rows}


def place_summary(cells):
    """ "114 statements = 81 of the short paper + 32 of the expanded version only + 1 retired" """
    expanded, retired = cells.count(NOT_IN_SHORT), cells.count(RETIRED)
    return (f"{len(cells)} statements = {len(cells) - expanded - retired} of the short paper (version {SHORT_VERSION})"
            f" + {expanded} of the expanded version only + {retired} retired")


def render(items, axioms_by_name):
    short = read_short_map()
    rows = [f"| # | Lean name | Short paper v{SHORT_VERSION} | Paper claim | Status | Cited axioms used |",
            "|---|---|---|---|---|---|"]
    counts = {}
    for idx, (name, doc) in enumerate(items, 1):
        axioms = axioms_by_name[name]
        status = classify(axioms)
        counts[status] = counts.get(status, 0) + 1
        cited = ", ".join(sorted(a.removeprefix("EulerFlow.Cited.") for a in axioms if a.startswith("EulerFlow.Cited.")))
        rows.append(f"| {idx} | `{name}` | {short[name]} | {doc} | {status} | {cited or '—'} |")
    summary = ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))
    summary += ". " + place_summary([short[name] for name, _ in items])
    return summary, "\n".join(rows), counts


def main_audit():
    items = parse_statements(STATEMENTS.read_text())
    names = [n for n, _ in items]
    write_audit_lean(names)
    axioms_by_name = parse_axioms(run_lean(), names)
    summary, table, counts = render(items, axioms_by_name)
    notes = AUDIT_NOTES.read_text() if AUDIT_NOTES.exists() else ""
    AUDIT_MD.write_text(f"# AUDIT — every claim of the paper, as Lean sees it\n\nGenerated by scripts/audit.py from "
                        f"`#print axioms`. Summary: {summary}.\n\n{TRUST_NOTE}\n\n{table}\n\n{notes}")
    print(f"AUDIT: {len(items)} claims. {summary}. Table: {AUDIT_MD}")
    if counts.get("VIOLATION"):
        sys.exit("AUDIT FAILED: a forbidden axiom appears (VIOLATION rows).")


def main_test():
    sample = "/-- **Lemma 9.9**: hello. -/\ntheorem foo : True := trivial\ntheorem bar : True := sorry\n"
    assert parse_statements(sample) == [("foo", "**Lemma 9.9**: hello."), ("bar", "")], parse_statements(sample)
    out = ("'EulerFlow.foo' depends on axioms: [propext,\n EulerFlow.Cited.x]\n"
           "'EulerFlow.bar' depends on axioms: [sorryAx]\n'EulerFlow.baz' does not depend on any axioms\n")
    got = parse_axioms(out, ["foo", "bar", "baz"])
    assert classify(got["foo"]) == "PROVED-FROM-CITED"
    assert classify(got["bar"]) == "OPEN"
    assert classify(got["baz"]) == "PROVED"
    assert classify({"propext", "evil"}) == "VIOLATION"
    assert classify({"sorryAx", "evil"}) == "VIOLATION"
    assert classify({"EulerFlow.Cited.Temp.y", "evil"}) == "VIOLATION"
    assert classify({"sorryAx", "EulerFlow.Cited.Temp.y", "evil"}) == "VIOLATION"
    assert classify({"propext", "EulerFlow.Cited.x", "EulerFlow.Cited.Temp.y"}) == "PROVED-FROM-TEMP"
    assert short_cell("Lemma 7.2", "l.5-6") == "Lemma 7.2, l.5-6"
    assert short_cell("NOT IN SHORT PAPER", "-") == NOT_IN_SHORT and short_cell("RETIRED", "-") == RETIRED
    assert place_summary(["Lemma 7.2, l.5-6", NOT_IN_SHORT, NOT_IN_SHORT, RETIRED]).startswith("4 statements = 1 of")
    print("PASS: audit.py self-test")


def main():
    if sys.argv[1:] == ["--test"]:
        main_test()
    elif not sys.argv[1:]:
        main_audit()
    else:
        sys.exit("Usage: scripts/audit.py [--test]")


if __name__ == "__main__":
    main()
