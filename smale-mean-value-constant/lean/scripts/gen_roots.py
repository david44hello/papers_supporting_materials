#!/usr/bin/env python3
"""gen_roots.py — write Smale/Proofs/DataRootsData.lean: a 40-digit rational point r near the zero z₁ ≈ 1.0000069 - 0.0015226i
of G (Newton in exact rationals, then rounded). Lean proves from r alone (kernel checks) that a zero lies within 1e-30 of r;
nothing here is trusted.
Usage: gen_roots.py <tex> <pair json> <out .lean>
"""
import cmath
import json
import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import gen_data  # noqa: E402
import gen_exact  # noqa: E402

DIGITS = 40
EPS = Fraction(1, 10 ** 30)


def newton_root(g0, g1, start):
    """Newton on G(z) = z² + g₁z + g₀ in exact Gaussian rationals, rounded to DIGITS decimals each step."""
    z = (Fraction(start.real).limit_denominator(10 ** 12), Fraction(start.imag).limit_denominator(10 ** 12))
    scale = 10 ** DIGITS
    for _ in range(8):
        val = gen_exact.padd(gen_exact.padd([gen_exact.gmul(z, z)], [gen_exact.gmul(g1, z)]), [g0])[0]
        der = (2 * z[0] + g1[0], 2 * z[1] + g1[1])
        den = der[0] ** 2 + der[1] ** 2
        step = gen_exact.gmul(val, (der[0] / den, -der[1] / den))
        z = (round((z[0] - step[0]) * scale) / Fraction(scale), round((z[1] - step[1]) * scale) / Fraction(scale))
    return z


def certified_radius_ok(g0, g1, r):
    """4|G(r)|² ≤ EPS²|G'(r)|², i.e. 2|G(r)|/|G'(r)| ≤ EPS."""
    val = gen_exact.padd(gen_exact.padd([gen_exact.gmul(r, r)], [gen_exact.gmul(g1, r)]), [g0])[0]
    der = (2 * r[0] + g1[0], 2 * r[1] + g1[1])
    return 4 * (val[0] ** 2 + val[1] ** 2) <= EPS ** 2 * (der[0] ** 2 + der[1] ** 2)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    sys.set_int_max_str_digits(0)
    printed = gen_data.printed_data(Path(sys.argv[1]).read_text())
    data = json.loads(Path(sys.argv[2]).read_text())
    q = [gen_data.parse_json_gauss(x) for x in data["Q_ascending"]]
    g0, g1 = gen_data.compute_g(gen_data.check_file(data, q), [printed[f"rho_{j}"] for j in range(1, 11)])
    disc = cmath.sqrt(complex(float(g1[0]), float(g1[1])) ** 2 - 4 * complex(float(g0[0]), float(g0[1])))
    roots = [(-complex(float(g1[0]), float(g1[1])) + sgn * disc) / 2 for sgn in (1, -1)]
    start = min(roots, key=lambda z: abs(z - 1))
    r = newton_root(g0, g1, start)
    if not certified_radius_ok(g0, g1, r):
        sys.exit("FAIL: the radius check fails at r")
    Path(sys.argv[3]).write_text(f"""/-
Smale/Proofs/DataRootsData.lean — a rational point `rG` within `10⁻³⁰` of the zero `z₁ ≈ 1.0000069 - 0.0015226 i` of `G`
(Lean checks this). GENERATED by scripts/gen_roots.py — do not edit by hand.
## version 0.11 - 20261027_2145 — public header (comments only).
## version 0.01 - 20261027_2040 — first version.
-/
import Smale.Proofs.DataGQ

namespace Smale.Exact

def rG : GQ := {gen_exact.lean_gq(r)}

end Smale.Exact
""")
    print(f"wrote {sys.argv[3]}: r = {float(r[0])} + {float(r[1])} i; other root ~ {-float(g1[0]) - float(r[0])} + "
          f"{-float(g1[1]) - float(r[1])} i")


if __name__ == "__main__":
    main()
