#!/usr/bin/env python3
"""gen_r_intervals.py — writes the interval modules of the Lean proof of fact (R): the cover of [0,1], and the matrix A of each interval.

Author: Dave Goel. Copyright (C) Dave Goel 2026--now.

The Lean proof does not depend on how this script finds its answers: the kernel checks each interval with the A written here, and soundness
holds for any A. Exact integers throughout; no floating point.

Interval: c = (a + tau)/D, D = 2^k, tau in [-1,1]. q_l(tau) = hbar_(l+1) D^(17-l) V_l(tau), V_(l+1) = 2(a+tau) V_l - D^2 V_(l-1), hbar = h rounded at 2^-64.
B_jk(tau) = B_(j-1,k-1) + q_j conj(q_k) - conj(q_(17-j)) q_(17-k) = sum_s B_s,jk tau^s. H_s = A B_s, G_s = H_s A*. The test, for each row j:
  Re G_0,jj > sum_(t != j) |G_0,jt| + sum_(1<=s<6) sum_t |G_s,jt| + sum_(s>=6) sum_k |H_s,jk| colSum_k + 2^93 D^34 rowSum_j totalA.
A is the inverse of the LDL* factor of B_0 at tau = 0, in fixed point, with its rows scaled by powers of two.

Usage: gen_r_intervals.py --noninteractive DATA_GQ_LEAN OUTDIR   (DATA_GQ_LEAN is Smale/Proofs/DataGQ.lean, which holds the exact coefficients)
       gen_r_intervals.py --test
"""
import argparse
import re
from fractions import Fraction as Fr
from pathlib import Path

M = 17
ORDER = 6
ETA = 1 << 93
FRAC_BITS = 64
HBAR_BITS = 64
CHUNK = 10
START_LEVEL = 2
MAX_LEVEL = 40
GENERATOR_NOTE = "Generated by scripts/gen_r_intervals.py."


def load_exact_h(path):
    """The list hGQ of Smale/Proofs/DataGQ.lean, as pairs of fractions."""
    source = Path(path).read_text()
    start = source.index("def hGQ : GP := [") + len("def hGQ : GP := [")
    body = source[start:source.index("]", start)]
    number = r"\((-?\d+)(?:/(\d+))?\s*:\s*ℚ\)"
    items = re.findall("⟨" + number + r",\s*" + number + "⟩", body)
    if len(items) != M + 2:
        raise SystemExit("expected %d coefficients in %s, found %d" % (M + 2, path, len(items)))
    return [(Fr(int(a), int(b) if b else 1), Fr(int(c), int(d) if d else 1)) for a, b, c, d in items]


def round_h(pairs):
    """hbar_1, ..., hbar_18: h rounded toward zero at 2^-64."""
    scale = 1 << HBAR_BITS
    return [(int(a * scale), int(b * scale)) for a, b in pairs[1:M + 2]]


def gabs1(x):
    return abs(x[0]) + abs(x[1])


def gmul(x, y):
    return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])


def v_tables(a, big_d):
    """V_0, ..., V_17 as lists of integer coefficients in tau."""
    tables = [[1], [2 * a, 2]]
    for _ in range(2, M + 1):
        new = [0] * (len(tables[-1]) + 1)
        for s, value in enumerate(tables[-1]):
            new[s] += 2 * a * value
            new[s + 1] += 2 * value
        for s, value in enumerate(tables[-2]):
            new[s] -= big_d * big_d * value
        tables.append(new)
    return tables


def q_polys(hbar, a, big_d):
    out = []
    for l, table in enumerate(v_tables(a, big_d)):
        factor = big_d ** (M - l)
        out.append([(hbar[l][0] * factor * v, hbar[l][1] * factor * v) for v in table])
    return out


def poly_mul(f, g, conj_f, conj_g):
    out = [(0, 0)] * (len(f) + len(g) - 1)
    for s, x in enumerate(f):
        x2 = (x[0], -x[1]) if conj_f else x
        for t, y in enumerate(g):
            z = gmul(x2, (y[0], -y[1]) if conj_g else y)
            out[s + t] = (out[s + t][0] + z[0], out[s + t][1] + z[1])
    return out


def b_tables(q):
    """b[s][j][k], s = 0, ..., 34."""
    size = 2 * M + 1
    poly = [[None] * M for _ in range(M)]
    for j in range(M):
        for k in range(j, M):
            f1 = poly_mul(q[j], q[k], False, True)
            f2 = poly_mul(q[M - j], q[M - k], True, False)
            total = [(0, 0)] * size
            if j >= 1:
                total = list(poly[j - 1][k - 1])
            for s, z in enumerate(f1):
                total[s] = (total[s][0] + z[0], total[s][1] + z[1])
            for s, z in enumerate(f2):
                total[s] = (total[s][0] - z[0], total[s][1] - z[1])
            poly[j][k] = total
    for j in range(M):
        for k in range(j):
            poly[j][k] = [(z[0], -z[1]) for z in poly[k][j]]
    return [[[poly[j][k][s] for k in range(M)] for j in range(M)] for s in range(size)]


def ldl_factors(fp):
    unit = 1 << FRAC_BITS
    ell = [[(0, 0)] * M for _ in range(M)]
    dee = [0] * M
    for i in range(M):
        total = fp[i][i][0]
        for k in range(i):
            lik = ell[i][k]
            total -= ((lik[0] * lik[0] + lik[1] * lik[1]) >> FRAC_BITS) * dee[k] >> FRAC_BITS
        if total <= 0:
            return None, None
        dee[i] = total
        ell[i][i] = (unit, 0)
        for j in range(i + 1, M):
            acc = fp[j][i]
            for k in range(i):
                z = gmul(ell[j][k], (ell[i][k][0], -ell[i][k][1]))
                acc = (acc[0] - ((z[0] >> FRAC_BITS) * dee[k] >> FRAC_BITS), acc[1] - ((z[1] >> FRAC_BITS) * dee[k] >> FRAC_BITS))
            ell[j][i] = ((acc[0] << FRAC_BITS) // total, (acc[1] << FRAC_BITS) // total)
    return ell, dee


def inverse_unit_lower(ell):
    unit = 1 << FRAC_BITS
    inv = [[(0, 0)] * M for _ in range(M)]
    for col in range(M):
        inv[col][col] = (unit, 0)
        for row in range(col + 1, M):
            acc = (0, 0)
            for k in range(col, row):
                z = gmul(ell[row][k], inv[k][col])
                acc = (acc[0] + (z[0] >> FRAC_BITS), acc[1] + (z[1] >> FRAC_BITS))
            inv[row][col] = (-acc[0], -acc[1])
    return inv


def make_a(b0):
    """A: lower triangular Gaussian integers; None if the fixed point LDL* fails."""
    top = max(max(gabs1(x) for x in row) for row in b0)
    shift = max(0, top.bit_length() - 2 * FRAC_BITS)
    ell, dee = ldl_factors([[(x[0] >> shift, x[1] >> shift) for x in row] for row in b0])
    if ell is None:
        return None
    inv = inverse_unit_lower(ell)
    scaled = []
    for j in range(M):
        drop = max(0, dee[j].bit_length() // 2 - FRAC_BITS // 2)
        scaled.append([(x[0] >> drop, x[1] >> drop) for x in inv[j]])
    return scaled


def left_mul(a_mat, mat):
    out = []
    for j in range(M):
        row = []
        for t in range(M):
            xs, ys = 0, 0
            for i in range(j + 1):
                z = gmul(a_mat[j][i], mat[i][t])
                xs, ys = xs + z[0], ys + z[1]
            row.append((xs, ys))
        out.append(row)
    return out


def right_conj(hmat, a_mat):
    out = []
    for j in range(M):
        row = []
        for t in range(M):
            xs, ys = 0, 0
            for i in range(t + 1):
                z = gmul(hmat[j][i], (a_mat[t][i][0], -a_mat[t][i][1]))
                xs, ys = xs + z[0], ys + z[1]
            row.append((xs, ys))
        out.append(row)
    return out


def row_passes(j, a_mat, hs, gs, col_sum, total_a, big_d_34):
    total = ETA * big_d_34 * sum(gabs1(x) for x in a_mat[j]) * total_a
    total += sum(gabs1(gs[0][j][t]) for t in range(M) if t != j)
    for s in range(1, ORDER):
        total += sum(gabs1(x) for x in gs[s][j])
    for s in range(ORDER, 2 * M + 1):
        total += sum(gabs1(hs[s][j][i]) * col_sum[i] for i in range(M))
    return gs[0][j][j][0] > total


def check_interval(hbar, a, k):
    """(passes, A)."""
    big_d = 1 << k
    bs = b_tables(q_polys(hbar, a, big_d))
    a_mat = make_a(bs[0])
    if a_mat is None:
        return False, None
    col_sum = [sum(gabs1(a_mat[t][i]) for t in range(M)) for i in range(M)]
    hs = [left_mul(a_mat, bs[s]) for s in range(2 * M + 1)]
    gs = [right_conj(hs[s], a_mat) for s in range(ORDER)]
    big_d_34 = 1 << (34 * k)
    passed = all(row_passes(j, a_mat, hs, gs, col_sum, sum(col_sum), big_d_34) for j in range(M))
    return passed, a_mat


def find_cover(hbar):
    """The dyadic intervals of [0,1], by bisection, each with its A, in increasing order."""
    stack = [(2 * i + 1, START_LEVEL) for i in range((1 << START_LEVEL) // 2 - 1, -1, -1)]
    cover = []
    while stack:
        a, k = stack.pop()
        passed, a_mat = check_interval(hbar, a, k)
        if passed:
            cover.append((a, k, a_mat))
            continue
        if k >= MAX_LEVEL:
            raise SystemExit("interval (%d, %d) fails at the deepest level" % (a, k))
        stack.append((2 * a + 1, k + 1))
        stack.append((2 * a - 1, k + 1))
    return cover


def lean_sn(value):
    return "(%s, %d)" % ("true" if value < 0 else "false", abs(value))


def lean_gs(pair):
    return "(%s, %s)" % (lean_sn(pair[0]), lean_sn(pair[1]))


def lean_a(a_mat):
    rows = ["[" + ", ".join(lean_gs(x) for x in row[: j + 1]) + "]" for j, row in enumerate(a_mat)]
    return "[" + ",\n  ".join(rows) + "]"


def module_head(name, line, imports):
    return ["/-", "Smale/R/%s.lean — %s %s" % (name, line, GENERATOR_NOTE), "-/"] + imports + ["namespace Smale.RK"]


def write_hb(outdir, hbar):
    lines = module_head("Hb", "The coefficients of H rounded at 2^-64.", ["import Smale.R.Checker"])
    lines += ["def hb : List GS := [" + ", ".join(lean_gs(x) for x in hbar) + "]", "end Smale.RK"]
    (outdir / "Hb.lean").write_text("\n".join(lines) + "\n")


def list_proof(chunk):
    proof = "fun _ h => absurd h List.not_mem_nil"
    for a, k, _ in reversed(chunk):
        proof = "List.forall_mem_cons.2 ⟨⟨_, t_%d_%d⟩, %s⟩" % (a, k, proof)
    return proof


def write_intervals(outdir, number, chunk):
    name = "Intervals%03d" % number
    lines = module_head(name, "Intervals of the cover of [0, 1], each with its matrix A and its kernel check.", ["import Smale.R.Hb"])
    for a, k, a_mat in chunk:
        lines.append("def a_%d_%d : List (List GS) := %s" % (a, k, lean_a(a_mat)))
        lines.append("theorem t_%d_%d : checkInterval hb %d %d %d a_%d_%d = true := by decide +kernel" % (a, k, a, k, ORDER, a, k))
    lines.append("def l%03d : List (Nat × Nat) := [%s]" % (number, ", ".join("(%d, %d)" % (a, k) for a, k, _ in chunk)))
    lines.append("theorem m%03d : ∀ e ∈ l%03d, ∃ A, checkInterval hb e.1 e.2 %d A = true :=" % (number, number, ORDER))
    lines.append("  " + list_proof(chunk))
    lines.append("end Smale.RK")
    (outdir / (name + ".lean")).write_text("\n".join(lines) + "\n")


def write_cover(outdir, count):
    imports = ["import Smale.R.Intervals%03d" % n for n in range(count)]
    lines = module_head("Cover", "The list of intervals, and the proof that all of them pass.", imports)
    joined = "l%03d" % (count - 1)
    proof = "m%03d" % (count - 1)
    for n in range(count - 2, -1, -1):
        joined = "l%03d ++ (%s)" % (n, joined)
        proof = "List.forall_mem_append.2 ⟨m%03d, %s⟩" % (n, proof)
    lines.append("def coverList : List (Nat × Nat) := " + joined)
    lines.append("theorem coverList_proved : ∀ e ∈ coverList, ∃ A, checkInterval hb e.1 e.2 %d A = true :=" % ORDER)
    lines += ["  " + proof, "end Smale.RK"]
    (outdir / "Cover.lean").write_text("\n".join(lines) + "\n")


def main_generate(data_path, outdir):
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    hbar = round_h(load_exact_h(data_path))
    cover = find_cover(hbar)
    write_hb(out, hbar)
    chunks = [cover[i:i + CHUNK] for i in range(0, len(cover), CHUNK)]
    for number, chunk in enumerate(chunks):
        write_intervals(out, number, chunk)
    write_cover(out, len(chunks))
    print("intervals %d, modules %d, written to %s" % (len(cover), len(chunks), out))


def run_tests():
    tables = v_tables(3, 8)
    c = Fr(3 + 1, 8)
    u = [Fr(1), 2 * c]
    for _ in range(2, M + 1):
        u.append(2 * c * u[-1] - u[-2])
    for l in range(M + 1):
        assert Fr(sum(tables[l]), 8 ** l) == u[l], l
    assert lean_gs((1, -2)) == "((false, 1), (true, 2))"
    print("PASS: all checks hold")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--noninteractive", nargs=2, metavar=("DATA_GQ_LEAN", "OUTDIR"))
    parser.add_argument("--test", action="store_true")
    args = parser.parse_args()
    if args.test:
        run_tests()
    elif args.noninteractive:
        main_generate(args.noninteractive[0], args.noninteractive[1])
    else:
        parser.error("give --noninteractive DATA_GQ_LEAN OUTDIR, or --test")


if __name__ == "__main__":
    main()
