#!/bin/bash
# mkroot.sh — write the root module Smale.lean: imports every module under Smale/ except the generated Smale.Audit
# (no declarations; kernel_replay.sh needs a root that declares nothing). Pattern of CerecedaLean's mkroot.sh.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
if ls -d Smale/Scratch* >/dev/null 2>&1; then echo "REFUSED: scratch folders present: $(ls -d Smale/Scratch*)"; exit 1; fi
{ echo "-- Smale.lean — root module of SmaleLean: imports every module, declares nothing (generated by scripts/mkroot.sh)."
  find Smale -name '*.lean' ! -path 'Smale/Audit.lean' | sort | sed 's|\.lean$||; s|/|.|g; s|^|import |'; } > Smale.lean
echo "wrote Smale.lean with $(grep -c '^import' Smale.lean) imports"
