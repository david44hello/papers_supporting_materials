#!/usr/bin/env python3
"""gen_margins.py — write the certificates for Remark 5.2 and the control experiment (paper 009, tex l.433-442):
  Smale/Proofs/SchurCertR.lean  Schur–Cohn certificate for H'(r w), r = 1.00001141 (formal degree 17): H' has no zero
                                with |z| <= 1.00001141;
  Smale/Proofs/RoucheCert.lean  two Rouché certificates: a zero of H' within 10^-14 of zH, and a zero of P_c,
                                c = 0.9231, within 10^-14 of zC (zH, zC: decimal approximations with 20 digits).
Python only proposes the data; every fact is checked by Lean's kernel (`decide +kernel`); Lean never trusts Python.
Usage: gen_margins.py <tex> <pair json> <out dir = .../Smale/Proofs>
       gen_margins.py --test
"""
import json
import sys
from fractions import Fraction
from math import isqrt
from pathlib import Path

import mpmath as mp

sys.path.insert(0, str(Path(__file__).parent))
import gen_data  # noqa: E402
import gen_exact  # noqa: E402
import gen_schur  # noqa: E402

ZERO = gen_exact.ZERO
R_SCHUR = Fraction(100001141, 100000000)  # r = 1.00001141
C_CTRL = Fraction(9231, 10000)             # c = 0.9231
RADIUS = Fraction(1, 10 ** 14)             # Rouché radius
DIGITS = 20                                # decimals of the centers zH, zC
SIG = 12                                   # significant digits of the norm bounds


def load_h(tex_path, pair_path):
    printed = gen_data.printed_data(tex_path.read_text())
    data = json.loads(pair_path.read_text())
    q = [gen_data.parse_json_gauss(x) for x in data["Q_ascending"]]
    gen_data.check_file(data, q)
    q = [tuple(Fraction(x) for x in c) for c in q]
    return gen_exact.compute_h(q, printed["a_1"], printed["a_2"])


def derivative(p):
    return [(k * c[0], k * c[1]) for k, c in enumerate(p)][1:]


def u_q(c, l):
    """U_l(c) by the recurrence of Lean's uQ."""
    u0, u1 = Fraction(1), 2 * c
    if l == 0:
        return u0
    for _ in range(l - 1):
        u0, u1 = u1, 2 * c * u1 - u0
    return u1


def pdieu(h, n, c):
    get = lambda k: h[k] if k < len(h) else ZERO  # noqa: E731
    return [gen_exact.gmul(get(l + 1), (u_q(c, l), Fraction(0))) for l in range(n)]


def taylor(p, z0):
    """Coefficients of u -> p(z0 + u) (Horner, as Lean's pcomp p [z0, 1])."""
    acc = []
    for c in reversed(p):
        acc = gen_exact.padd([c], gen_exact.pmul([z0, (Fraction(1), Fraction(0))], acc) if acc else [])
    return acc


def nsq(z):
    return z[0] * z[0] + z[1] * z[1]


def sqrt_bound(q, up):
    """A decimal u with SIG significant digits and u^2 >= q (up) or u^2 <= q, u >= 0 (down); exact check."""
    if q == 0:
        return Fraction(0)
    mag = int(mp.floor(mp.log10(mp.sqrt(mp.mpf(q.numerator) / q.denominator))))
    scale = Fraction(10) ** (SIG - 1 - mag)
    big = q * scale * scale
    root = isqrt(big.numerator // big.denominator)
    if up:
        while Fraction(root) ** 2 < big:
            root += 1
    out = Fraction(root) / scale
    if (up and out * out < q) or (not up and out * out > q):
        sys.exit("FAIL: sqrt bound")
    return out


def nearest_zero(p, near):
    coeffs = [mp.mpc(mp.mpf(c[0].numerator) / c[0].denominator, mp.mpf(c[1].numerator) / c[1].denominator)
              for c in p]
    roots = mp.polyroots(list(reversed(coeffs)), maxsteps=500, extraprec=600)
    return min(roots, key=lambda z: abs(z - near))


def rationalize(z):
    scale = 10 ** DIGITS
    return (Fraction(int(mp.nint(z.real * scale)), scale), Fraction(int(mp.nint(z.imag * scale)), scale))


def rouche(p, z0):
    """T = Taylor coefficients at z0; upper bounds u_k (k != 1), lower bound l; checks the Rouché inequality."""
    t = taylor(p, z0)
    us = [Fraction(0) if k == 1 else sqrt_bound(nsq(c), True) for k, c in enumerate(t)]
    low = sqrt_bound(nsq(t[1]), False)
    lhs = sum(us[k] * RADIUS ** k for k in range(len(t)) if k != 1)
    if not lhs < low * RADIUS:
        sys.exit("FAIL: Rouché inequality")
    return t, us, low


def lean_list(p):
    return "[\n  " + ",\n  ".join(gen_exact.lean_gq(z) for z in p) + "]"


def lean_qlist(xs):
    return "[" + ", ".join(gen_data.lean_q(x) for x in xs) + "]"


def render_schur(gs, cs):
    gen_schur.BASE_EQ["hr"] = "rfl"
    base = f"pcomp (pderiv hGQ) [GQ.zero, GQ.ofQ {gen_data.lean_q(R_SCHUR)}]"
    text = gen_schur.render("hr", "H'(r w), r = 1.00001141", base, f"toPoly ({base})", 17, gs, cs)
    head, body = text.split("-/\n", 1)
    head = ("/-\nSmale/Proofs/SchurCertR.lean — Schur–Cohn certificate for H'(r w), r = 1.00001141 (formal degree 17;\n"
            "Remark 5.2, tex l.434-435): normalized iterates g_j and positive scales c_j with T g_j = c_j g_{j+1}, each\n"
            "step checked by the kernel; the constant terms of g_1, …, g_17 are real and positive. GENERATED by\n"
            "scripts/gen_margins.py — do not edit by hand.\n## version 0.01 - 20261028_0330 — first version.\n")
    body = body.replace("import Smale.Proofs.SchurList\nimport Smale.Proofs.DataPoly", "import Smale.Proofs.RoucheGP")
    return head + "-/\n" + body


def render_cert(tag, t, us, low, z0, zbounds):
    upper, lower = zbounds
    return f"""
/-- The center `z{tag}`. -/
def z{tag} : GQ := {gen_exact.lean_gq(z0)}

/-- The Taylor coefficients at `z{tag}`. -/
def t{tag} : GP := {lean_list(t)}

/-- Upper bounds for `|t_k|` (`k ≠ 1`). -/
def u{tag} : List ℚ := {lean_qlist(us)}

/-- A lower bound for `|t_1|`. -/
def l{tag} : ℚ := {gen_data.lean_q(low)}

theorem c{tag}_l : l{tag} * l{tag} ≤ (t{tag}.getD 1 GQ.zero).nsq := by decide +kernel

theorem c{tag}_us : ∀ k ∈ Finset.range t{tag}.length, k ≠ 1 →
    0 ≤ u{tag}.getD k 0 ∧ (t{tag}.getD k GQ.zero).nsq ≤ u{tag}.getD k 0 * u{tag}.getD k 0 := by decide +kernel

theorem c{tag}_sum : ∑ k ∈ Finset.range t{tag}.length, (if k = 1 then 0 else u{tag}.getD k 0 * rRadius ^ k) <
    l{tag} * rRadius := by decide +kernel

/-- `{gen_data.lean_q(lower)} ≤ |z{tag}| ≤ {gen_data.lean_q(upper)}`. -/
theorem c{tag}_z : {gen_data.lean_q(lower)} * {gen_data.lean_q(lower)} ≤ z{tag}.nsq ∧
    z{tag}.nsq ≤ {gen_data.lean_q(upper)} * {gen_data.lean_q(upper)} := by decide +kernel
"""


def render_rouche(cert_h, cert_c):
    return f"""/-
Smale/Proofs/RoucheCert.lean — two Rouché certificates (Remark 5.2 and the control, tex l.434-442): the Taylor
coefficients of H' at zH and of P_c, c = 0.9231, at zC (each expansion checked by the kernel against Lean's own
`pcomp`), with exact rational bounds for `exists_root_of_cert`. GENERATED by scripts/gen_margins.py — do not edit
by hand.
## version 0.01 - 20261028_0330 — first version.
-/
import Smale.Proofs.RoucheGP

namespace Smale.Exact

open Polynomial Complex

/-- The Rouché radius `10⁻¹⁴`. -/
def rRadius : ℚ := {gen_data.lean_q(RADIUS)}
{cert_h}
theorem tH_eq : peq (pcomp (pderiv hGQ) [zH, ⟨1, 0⟩]) tH = true := by decide +kernel
{cert_c}
theorem tC_eq : peq (pcomp (pdieu hGQ 18 {gen_data.lean_q(C_CTRL)}) [zC, ⟨1, 0⟩]) tC = true := by decide +kernel

end Smale.Exact
"""


def z_bounds(z0):
    return sqrt_bound(nsq(z0), True), sqrt_bound(nsq(z0), False)


def main_gen(tex_path, pair_path, out_dir):
    mp.mp.dps = 80
    h = load_h(tex_path, pair_path)
    hder = derivative(h)
    f = [(c[0] * R_SCHUR ** k, c[1] * R_SCHUR ** k) for k, c in enumerate(hder)]
    gs, cs = gen_schur.certificate(f, 17)
    (out_dir / "SchurCertR.lean").write_text(render_schur(gs, cs))
    zh = rationalize(nearest_zero(hder, mp.mpc(-0.4885, -0.8726)))
    pc = pdieu(h, 18, C_CTRL)
    zc = rationalize(nearest_zero(pc, mp.mpc(0.4089, 0.9126)))
    t_h, us_h, low_h = rouche(hder, zh)
    t_c, us_c, low_c = rouche(pc, zc)
    text = render_rouche(render_cert("H", t_h, us_h, low_h, zh, z_bounds(zh)),
                         render_cert("C", t_c, us_c, low_c, zc, z_bounds(zc)))
    (out_dir / "RoucheCert.lean").write_text(text)
    for name, z0 in (("zH", zh), ("zC", zc)):
        print(f"{name} = {float(z0[0])} + {float(z0[1])} i, |{name}| - 1 = {float(mp.sqrt(mp.mpf(nsq(z0).numerator) / nsq(z0).denominator) - 1):.12e}")
    print(f"wrote {out_dir / 'SchurCertR.lean'} and {out_dir / 'RoucheCert.lean'}")


def run_tests():
    one = (Fraction(1), Fraction(0))
    p = [(Fraction(-2), Fraction(0)), ZERO, one]  # z^2 - 2: zero sqrt 2
    z0 = (Fraction(14142135623730950488, 10 ** 19), Fraction(0))
    t, us, low = rouche(p, z0)
    assert len(t) == 3 and low > 0, (t, us, low)
    assert abs(float(u_q(Fraction(1, 2), 2)) - 0.0) < 1e-12  # U_2(1/2) = 4/4 - 1 = 0
    print("tests PASS")


def main():
    if sys.argv[1:] == ["--test"]:
        run_tests()
        return
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    sys.set_int_max_str_digits(0)
    main_gen(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))


if __name__ == "__main__":
    main()
