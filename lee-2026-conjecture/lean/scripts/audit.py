#!/usr/bin/env python3
"""audit.py — status of every claim in LeeDiam/Paper/Statements.lean, read from Lean's `#print axioms`.
Author: Dave Goel. Copyright (C) Dave Goel 2026--now.
Usage: audit.py <core> --oleans scratch|lake
  scratch: scripts/lc.sh oleans first (compile Statements.lean and its imports with lc.sh before); lake: after lake build."""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OLEAN = ROOT / '.lake' / 'scratch' / 'olean'
STD = {'propext', 'Classical.choice', 'Quot.sound'}
CITED = {'LeeDiam.Cited.adjacency_ideals', 'LeeDiam.Cited.adjacency_antichains'}


def claim_names():
    src = (ROOT / 'LeeDiam/Paper/Statements.lean').read_text()
    return re.findall(r'^theorem (\S+)', src, re.M)


def search_path(mode):
    lean_path = subprocess.run(['lake', 'env', 'printenv', 'LEAN_PATH'], cwd=ROOT, capture_output=True,
                               text=True, check=True).stdout.strip()
    return {'scratch': f'{OLEAN}:{lean_path}', 'lake': lean_path}[mode]


def run_probe(core, names, mode):
    probe = ROOT / 'scripts' / 'AuditProbe.lean'
    probe.write_text('import LeeDiam.Paper.Statements\n' + ''.join(f'#print axioms LeeDiam.{nm}\n' for nm in names))
    env = {'LEAN_PATH': search_path(mode), 'LEAN_NUM_THREADS': '1', 'PATH': '/usr/bin:/bin:' + str(Path.home() / '.elan/bin')}
    out = subprocess.run(['nice', '-n', '19', 'taskset', '-c', str(core), 'lean', str(probe)], cwd=ROOT,
                         capture_output=True, text=True, env=env)
    probe.unlink()
    if out.returncode != 0:
        raise SystemExit('probe failed:\n' + out.stdout + out.stderr)
    return out.stdout


def classify(text, names):
    status = {}
    for nm in names:
        m = re.search(rf"'LeeDiam\.{re.escape(nm)}' depends on axioms: \[(.*?)\]", text, re.S)
        if m:
            axs = {a.strip() for a in m.group(1).replace('\n', ' ').split(',') if a.strip()}
        elif re.search(rf"'LeeDiam\.{re.escape(nm)}' does not depend on any axioms", text):
            axs = set()
        else:
            raise SystemExit(f'no axiom line for {nm}')
        if 'sorryAx' in axs:
            status[nm] = ('OPEN', axs)
        elif axs <= STD:
            status[nm] = ('PROVED', axs)
        elif axs <= STD | CITED:
            status[nm] = ('PROVED-FROM-CITED', axs)
        else:
            status[nm] = ('VIOLATION', axs)
    return status


def write_report(status):
    counts = {k: sum(1 for v in status.values() if v[0] == k) for k in ('PROVED', 'PROVED-FROM-CITED', 'OPEN', 'VIOLATION')}
    lines = ['# AUDIT — LeeDiam, generated by scripts/audit.py from `#print axioms`', '',
             f'PROVED {counts["PROVED"]} / PROVED-FROM-CITED {counts["PROVED-FROM-CITED"]} / OPEN {counts["OPEN"]} / VIOLATION {counts["VIOLATION"]} '
             f'(of {len(status)} claims)', '', '| # | Claim | Status | Axioms |', '|---|---|---|---|']
    for idx, (nm, (st, axs)) in enumerate(status.items(), 1):
        lines.append(f'| {idx} | `{nm}` | {st} | {", ".join(sorted(axs))} |')
    (ROOT / 'AUDIT.md').write_text('\n'.join(lines) + '\n')
    print(lines[2])


def main():
    if len(sys.argv) != 4 or sys.argv[2] != '--oleans' or sys.argv[3] not in ('scratch', 'lake'):
        raise SystemExit('usage: audit.py <core> --oleans scratch|lake')
    names = claim_names()
    status = classify(run_probe(int(sys.argv[1]), names, sys.argv[3]), names)
    write_report(status)


if __name__ == '__main__':
    main()
