#!/bin/bash
# mkroot.sh — write the root module LeeDiam.lean: imports every module under LeeDiam/ (no declarations; kernel_replay
# needs a root that declares nothing). Refuses if a Scratch* folder exists.
# Author: Dave Goel. Copyright (C) Dave Goel 2026--now.
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
if ls -d LeeDiam/Scratch* >/dev/null 2>&1; then echo "REFUSED: scratch folders present: $(ls -d LeeDiam/Scratch*)"; exit 1; fi
{ echo "-- LeeDiam.lean — root module of LeeDiamLean: imports every module, declares nothing (generated by scripts/mkroot.sh)."
  find LeeDiam -name '*.lean' | sort | sed 's|\.lean$||; s|/|.|g; s|^|import |'; } > LeeDiam.lean
echo "wrote LeeDiam.lean with $(grep -c '^import' LeeDiam.lean) imports"
