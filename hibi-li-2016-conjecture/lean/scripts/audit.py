#!/usr/bin/env python3
"""audit.py — the coverage-and-assumptions table for every paper claim, produced by Lean itself.
Author: Dave Goel. Copyright (C) Dave Goel 2026--now.

For every `theorem` in HibiLi/Paper/Statements.lean this script asks Lean (`#print axioms`) which axioms the proof
depends on, and classifies it:
  PROVED            only Lean's three standard axioms (propext, Classical.choice, Quot.sound)
  PROVED-FROM-CITED standard axioms plus HibiLi.Cited.* axioms (the paper's cited results) — listed by name
  PROVED-FROM-TEMP  uses a HibiLi.Cited.Temp.* axiom: a fact the paper PROVES that Lean has not proved yet — NOT done
  OPEN              depends on sorryAx (a proof gap somewhere below it)
  VIOLATION         any other axiom (forbidden; fails loudly)
Usage: scripts/audit.py            (writes AUDIT.md, exits 1 on any VIOLATION)
       scripts/audit.py --test     (self-test of the parser)
"""
import re
import subprocess
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
STATEMENTS = PROJECT / "HibiLi" / "Paper" / "Statements.lean"
AUDIT_LEAN = PROJECT / "HibiLi" / "Audit.lean"
AUDIT_MD = PROJECT / "AUDIT.md"
STANDARD = {"propext", "Classical.choice", "Quot.sound"}
NAMESPACE = "HibiLi.Paper"
# The results the formal proof may assume: cited and not proved by the paper (paper v2.10, Outline l. 179-185, and the
# places they are used); nothing else may be used. [CJK, Lemma 2] is not among them: v2.10 proves it, and so does Lean.
PAPER_CITED = frozenset("HibiLi.Cited." + name for name in (
    "hibiLi_thm_2_1", "ziegler_face_figure", "fourier_lemma_4_1", "fourier_prop_5_2",
    "hlss_thm_2_1"))
TRUST_NOTE = ("**Trust.** A row is conditional on exactly the cited axioms listed in its last column (PROVED rows on "
              "none); the cited axioms live in HibiLi/Cited/ (Fourier arXiv:2609.23629v1 "
              "Lemma 4.1 and Proposition 5.2 — an unrefereed preprint; Hibi–Li 2016 Theorem 2.1; HLSS 2017 Theorem 2.1; "
              "Ziegler Ch. 2 face figures). Casabella–Joswig–Kastner 2025 Lemma 2 (dual graphs) is cited by the paper and "
              "PROVED in Lean (HibiLi/Polytope/CJKProof.lean). A PROVED-FROM-TEMP row would rest on a placeholder for a "
              "fact the paper proves (namespace HibiLi.Cited.Temp); such rows are NOT counted as proved.")


def parse_statements(text):
    """Return [(name, doc_first_line)] for every top-level theorem, in file order."""
    items = []
    doc = ""
    for block in re.finditer(r"(/--(.*?)-/\s*)?^theorem\s+([\w']+)", text, re.S | re.M):
        doc = " ".join((block.group(2) or "").split())
        items.append((block.group(3), doc[:140]))
    return items


def write_audit_lean(names):
    lines = ["-- GENERATED by scripts/audit.py — do not edit.", "import HibiLi.Paper.Statements", ""]
    lines += [f"#print axioms {NAMESPACE}.{name}" for name in names]
    content = "\n".join(lines) + "\n"
    # Rewrite only on change: an identical rewrite leaves Lake's (content-hash) build fresh but makes the source
    # newer than its olean, and scripts/kernel_replay.sh then refuses the run as stale.
    if not AUDIT_LEAN.exists() or AUDIT_LEAN.read_text() != content:
        AUDIT_LEAN.write_text(content)


def run_lean():
    proc = subprocess.run(["nice", "-n", "19", "lake", "build", "HibiLi.Audit"],
                          cwd=PROJECT, capture_output=True, text=True, env=None)
    if proc.returncode != 0:
        sys.exit("AUDIT FAILED: Lean reported an error:\n" + proc.stdout + proc.stderr)
    return proc.stdout + proc.stderr


def parse_axioms(output, names):
    """Map each theorem name to its set of axioms, from `#print axioms` output."""
    result = {}
    pattern = re.compile(r"'([\w.']+)' (?:depends on axioms: \[(.*?)\]|does not depend on any axioms)", re.S)
    for match in pattern.finditer(output):
        full = match.group(1)
        short = full.removeprefix(NAMESPACE + ".")
        axioms = {a.strip() for a in (match.group(2) or "").replace("\n", " ").split(",") if a.strip()}
        result[short] = axioms
    missing = [n for n in names if n not in result]
    if missing:
        sys.exit(f"AUDIT FAILED: no #print axioms output for {missing}")
    return result


def classify(axioms):
    forbidden = {name for name in axioms - STANDARD - {"sorryAx"}
                 if not name.startswith("HibiLi.Cited.")}
    if forbidden:
        return "VIOLATION"
    if "sorryAx" in axioms:
        return "OPEN"
    if any(a.startswith("HibiLi.Cited.Temp.") for a in axioms):
        return "PROVED-FROM-TEMP"
    extra = axioms - STANDARD
    if not extra:
        return "PROVED"
    if all(a.startswith("HibiLi.Cited.") for a in extra):
        return "PROVED-FROM-CITED"
    return "VIOLATION"


def render(items, axioms_by_name):
    rows = ["| # | Lean name | Paper claim | Status | Cited axioms used |", "|---|---|---|---|---|"]
    counts = {}
    for idx, (name, doc) in enumerate(items, 1):
        axioms = axioms_by_name[name]
        status = classify(axioms)
        counts[status] = counts.get(status, 0) + 1
        cited = ", ".join(sorted(a.removeprefix("HibiLi.Cited.") for a in axioms if a.startswith("HibiLi.Cited.")))
        rows.append(f"| {idx} | `{name}` | {doc} | {status} | {cited or '—'} |")
    summary = ", ".join(f"{k}: {v}" for k, v in sorted(counts.items()))
    return summary, "\n".join(rows), counts


def check_paper_cited(axioms_by_name):
    """Fail if a cited axiom outside PAPER_CITED is used; warn if the paper names one that no claim uses."""
    used = {a for axioms in axioms_by_name.values() for a in axioms if a.startswith("HibiLi.Cited.")}
    if used - PAPER_CITED:
        sys.exit(f"AUDIT FAILED: cited axioms not named in the paper's Lean sentence: {sorted(used - PAPER_CITED)}")
    if PAPER_CITED - used:
        print(f"WARNING: the paper names assumptions that no claim uses: {sorted(PAPER_CITED - used)}")
    hlss = sorted(name for name, axioms in axioms_by_name.items() if "HibiLi.Cited.hlss_thm_2_1" in axioms)
    print(f"AUDIT: claims that use HLSS (the paper: only the statement on edges): {hlss}")


def main_audit():
    items = parse_statements(STATEMENTS.read_text())
    names = [n for n, _ in items]
    write_audit_lean(names)
    axioms_by_name = parse_axioms(run_lean(), names)
    summary, table, counts = render(items, axioms_by_name)
    check_paper_cited(axioms_by_name)
    AUDIT_MD.write_text(f"# AUDIT — every claim of the paper, as Lean sees it\n\nGenerated by scripts/audit.py from "
                        f"`#print axioms`. Summary: {summary}.\n\n{TRUST_NOTE}\n\n{table}\n")
    print(f"AUDIT: {len(items)} claims. {summary}. Table: {AUDIT_MD}")
    if counts.get("VIOLATION"):
        sys.exit("AUDIT FAILED: a forbidden axiom appears (VIOLATION rows).")


def main_test():
    sample = ("/-- **Lemma 9.9**: hello. -/\ntheorem foo : True := trivial\ntheorem bar : True := sorry\n"
              "theorem qux' : True := trivial\n")
    assert parse_statements(sample) == [("foo", "**Lemma 9.9**: hello."), ("bar", ""), ("qux'", "")], \
        parse_statements(sample)
    out = ("'HibiLi.Paper.foo' depends on axioms: [propext,\n HibiLi.Cited.x]\n"
           "'HibiLi.Paper.bar' depends on axioms: [sorryAx]\n'HibiLi.Paper.baz' does not depend on any axioms\n"
           "'HibiLi.Paper.qux'' does not depend on any axioms\n")
    got = parse_axioms(out, ["foo", "bar", "baz", "qux'"])
    assert classify(got["qux'"]) == "PROVED"
    assert classify(got["foo"]) == "PROVED-FROM-CITED"
    assert classify(got["bar"]) == "OPEN"
    assert classify(got["baz"]) == "PROVED"
    assert classify({"propext", "evil"}) == "VIOLATION"
    assert classify({"sorryAx", "evil"}) == "VIOLATION"
    assert classify({"HibiLi.Cited.Temp.y", "evil"}) == "VIOLATION"
    assert classify({"sorryAx", "HibiLi.Cited.Temp.y", "evil"}) == "VIOLATION"
    assert classify({"propext", "HibiLi.Cited.x", "HibiLi.Cited.Temp.y"}) == "PROVED-FROM-TEMP"
    check_paper_cited({"foo": {"propext", "HibiLi.Cited.hlss_thm_2_1"}})
    try:
        check_paper_cited({"foo": {"HibiLi.Cited.not_in_the_paper"}})
        raise AssertionError("an unlisted cited axiom must fail")
    except SystemExit:
        pass
    print("PASS: audit.py self-test")


def main():
    if sys.argv[1:] == ["--test"]:
        main_test()
    elif not sys.argv[1:]:
        main_audit()
    else:
        sys.exit("Usage: scripts/audit.py [--test]")


if __name__ == "__main__":
    main()
