#!/bin/bash
# mkroot.sh — write the root module Cereceda.lean: imports every module under Cereceda/ (no declarations; kernel_replay
# needs a root that declares nothing). Refuses if a Scratch* folder exists. 20261027.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
if ls -d Cereceda/Scratch* >/dev/null 2>&1; then echo "REFUSED: scratch folders present: $(ls -d Cereceda/Scratch*)"; exit 1; fi
{ echo "-- Cereceda.lean — root module of CerecedaLean: imports every module, declares nothing (generated by scripts/mkroot.sh)."
  find Cereceda -name '*.lean' | sort | sed 's|\.lean$||; s|/|.|g; s|^|import |'; } > Cereceda.lean
echo "wrote Cereceda.lean with $(grep -c '^import' Cereceda.lean) imports"
